insert into public.alimentos_antes_taco (id, porcao_g, calorias, proteina, carboidrato, gordura)
select a.id, a.porcao_g, a.calorias, a.proteina, a.carboidrato, a.gordura
from public.alimentos a
where a.taco_id is not null and not exists (select 1 from public.alimentos_antes_taco x where x.id = a.id);

-- Macros da TACO na porção que o alimento já tinha (calorias é inteiro na
-- tabela). Só onde a TACO mediu o valor: null na TACO mantém o atual.
update public.alimentos a set
  calorias    = coalesce(round(t.kcal * a.porcao_g / 100.0)::int, a.calorias),
  proteina    = coalesce(round(t.proteina * a.porcao_g / 100.0, 1), a.proteina),
  carboidrato = coalesce(round(t.carboidrato * a.porcao_g / 100.0, 1), a.carboidrato),
  gordura     = coalesce(round(t.lipidios * a.porcao_g / 100.0, 1), a.gordura)
from public.taco t
where a.taco_id = t.id and a.porcao_g > 0;

