create or replace function public.normalizar_texto(p text)
returns text
language sql
immutable
set search_path to 'public'
as $function$
  select regexp_replace(
    lower(translate(
      replace(replace(replace(replace(coalesce(p, ''), 'œ', 'oe'), 'Œ', 'oe'), 'æ', 'ae'), 'Æ', 'ae'),
      'ÁÀÂÃÄÉÈÊËÍÌÎÏÓÒÔÕÖÚÙÛÜÇÑŸáàâãäéèêëíìîïóòôõöúùûüçñÿँ़',
      'AAAAAEEEEIIIIOOOOOUUUUCNYaaaaaeeeeiiiiooooouuuucnyं')),
    '[^a-z0-9ऀ-ॿ]+', ' ', 'g');
$function$;
-- (o nukta "़" some no translate — "फ़" e "फ" viram o mesmo; "ँ" vira "ं")

