-- ATHOSlife — alimentos em francês (fr) e hindi (hi) + busca e filtro nos dois idiomas (dono, 28/10).
-- 1) normalizar_texto passa a manter a escrita devanágari (antes apagava tudo
--    que não fosse a-z: uma busca em hindi virava espaço e casava com qualquer
--    coisa) e troca œ/æ por oe/ae. O resultado em letras latinas fica igual.
-- 2) nome_fr / nome_hi em alimentos (chave: nome_en). Marcas regionais ficam
--    sem: o app mostra o nome em inglês (que é o nome da marca).
-- 3) buscar_alimentos acha e mostra pelo nome do idioma da pessoa.
-- 4) habito_nome_proibido ganha termos em francês e hindi (e o hinglish).
-- Rodar de novo é seguro.

